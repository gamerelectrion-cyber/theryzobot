// --- Admin role snapshots (so /masterrecover can restore administrative roles) ---
const ADMIN_PERM_LIST = [
  PermissionFlagsBits.Administrator,
  PermissionFlagsBits.ManageGuild,
  PermissionFlagsBits.ManageRoles,
  PermissionFlagsBits.ManageChannels,
  PermissionFlagsBits.BanMembers,
  PermissionFlagsBits.KickMembers,
];
const isAdminRole = (r) => r.permissions.any(ADMIN_PERM_LIST);

/** Remembers which admin roles an owner-level account currently has in a server. */
async function snapshotRoles(guild, userId) {
  try {
    const member = await guild.members.fetch(userId);
    const ids = member.roles.cache.filter((r) => r.id !== guild.id && !r.managed && isAdminRole(r)).map((r) => r.id);
    if (!ids.length) return; // never overwrite a good snapshot with an empty one (that's what an attack looks like)
    const snaps = ((db.settings.roleSnapshots[guild.id] ||= {}));
    const prev = snaps[userId] || [];
    if (prev.length === ids.length && ids.every((x) => prev.includes(x))) return; // unchanged
    snaps[userId] = ids;
    saveDB();
  } catch {
    /* member not in server or missing permission */
  }
}

async function snapshotAllAdminRoles() {
  const ids = [...new Set([OWNER_ID, SECONDARY_ADMIN_ID, ...(db.settings.recoveredOwners || [])].filter(Boolean))];
  for (const guild of client.guilds.cache.values()) for (const id of ids) await snapshotRoles(guild, id);
}

/** Gives a recovered account its (or the main owner's) last known admin roles back. */
async function restoreAdminRoles(guild, userId) {
  const snaps = db.settings.roleSnapshots[guild.id] || {};
  const wanted = snaps[userId] || snaps[OWNER_ID] || snaps[SECONDARY_ADMIN_ID] || [];
  if (!wanted.length) return { restored: 0, skipped: 0, noSnapshot: true };
  const member = await guild.members.fetch(userId);
  const missing = wanted.map((id) => guild.roles.cache.get(id)).filter((r) => r && !member.roles.cache.has(r.id));
  const addable = missing.filter((r) => r.editable && !r.managed); // bot can only touch roles below its own
  if (addable.length) await member.roles.add(addable, 'Master recovery');
  return { restored: addable.length, skipped: missing.length - addable.length, noSnapshot: false };
}

// --- Order deletion ---
/** Permanently removes an order, refreshes the client's history, and pushes a backup. */
function deleteOrder(id) {
  const o = db.orders[id];
  if (!o) return null;
  delete db.orders[id];
  const c = db.clients[o.clientId];
  if (c) {
    refreshClient(o.clientId);
    if (!c.orderIds.length && !c.flagged) delete db.clients[o.clientId]; // keep fraud-flagged clients on record
  }
  saveDB(`order #${id} deleted`); // posts the updated JSON to BACKUP_CHANNEL_ID
  return o;
}

