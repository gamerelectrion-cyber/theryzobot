/**
 * Client records are keyed by DISCORD USER ID (never by name), so the same person can never be
 * duplicated. Each record keeps the full order history and cumulative spend.
 */
function upsertClient(userId, name, createdAt) {
  const c = (db.clients[userId] ||= {
    userId,
    names: [],
    firstOrderAt: createdAt,
    fraudCount: 0,
    flagged: false,
    orderIds: [],
    totalSpent: { USD: 0, EUR: 0 },
    totalBilled: { USD: 0, EUR: 0 },
  });
  c.userId = userId;
  c.orderIds ||= [];
  c.totalSpent ||= { USD: 0, EUR: 0 };
  c.totalBilled ||= { USD: 0, EUR: 0 };
  c.ignored ??= false; // client-level ignore state used by /clientinfo and /clientlist
  if (name) {
    const cleanName = String(name).trim();
    c.displayName = cleanName;
    c.names = [...new Set((Array.isArray(c.names) ? c.names : []).filter(Boolean).map((n) => String(n).trim()))];
    if (cleanName && !c.names.some((n) => n.toLowerCase() === cleanName.toLowerCase())) c.names.push(cleanName);
  }
  if (createdAt && (!c.firstOrderAt || createdAt < c.firstOrderAt)) c.firstOrderAt = createdAt;
  return c;
}

/** Rebuilds a client's order history + cumulative spend from their orders (always consistent). */
function refreshClient(userId) {
  const c = db.clients[userId];
  if (!c) return;
  const mine = Object.values(db.orders).filter((o) => o.clientId === userId);
  c.orderIds = mine.map((o) => o.id);
  c.totalSpent = sumRevenue(mine.filter((o) => o.paymentStatus === 'Paid'));
  c.totalBilled = sumRevenue(mine.filter((o) => o.paymentStatus !== 'Fraud / Scammed'));
}

/** Converts any older/partial database into the current (v2) structure. */
function migrate(raw) {
  const d = Object.assign(emptyDB(), raw || {});
  d.version = 2;
  d.orders ||= {};
  d.clients ||= {};
  d.payouts ||= [];
  d.giveaways ||= [];
  d.settings ||= {};
  d.settings.invites ||= {};         // cached server invite links
  d.settings.access ||= {};          // NEW: helper permissions { userId: ['queue','setwork'] }
  d.settings.recoveredOwners ||= []; // NEW: accounts promoted by /masterrecover
  d.settings.roleSnapshots ||= {};   // NEW: last known admin roles per server/user
  d.settings.customStatus ??= null;   // optional timed custom bot status
  delete d.stats; // old counters are now derived from the orders themselves

  const prev = db;
  db = d; // so upsertClient writes into the new object
  for (const o of Object.values(d.orders)) {
    o.currency ||= 'USD';
    o.paymentMethod ||= 'Other';
    o.createdAt = toMs(o.createdAt) || Date.now();
    o.deadlineAt = toMs(o.deadlineAt);
    o.paidAt = toMs(o.paidAt);
    o.paymentDate = toMs(o.paymentDate); // optional promised payment date; old orders remain compatible
    if (!o.paymentStatus) {
      // v1 -> v2 status conversion
      if (o.status === 'Paid') {
        o.paymentStatus = 'Paid';
        o.paidAt ||= o.createdAt;
      } else o.paymentStatus = 'Pending Payment';
      o.workStatus =
        o.status === 'Thumbnail Completed' ? 'Completed' : o.status === 'Revision Requested' ? 'In Revision' : 'In Progress';
      if (o.completedLogged) {
        o.firstDeliveredAt = o.createdAt;
        if (o.workStatus === 'In Progress') o.workStatus = 'Completed';
      }
      delete o.status;
      delete o.completedLogged;
    }
    o.workStatus ||= 'In Progress';
    o.firstDeliveredAt = toMs(o.firstDeliveredAt);
    o.completedAt = toMs(o.completedAt);
    o.ignorePayment ??= false;
    o.reminderStage ??= 0;
    o.warned6h ??= false;
    o.missedAlerted ??= false;
    o.paidOut ??= false;
    o.earlyFinishHours ??= null; // NEW: hours before the deadline the order was first delivered
    o.workStartedAt ??= null;    // NEW: when /setwork made it the active order
    o.log ||= [];
    upsertClient(o.clientId, o.clientName, o.createdAt);
  }
  for (const id of Object.keys(d.clients)) refreshClient(id); // NEW: rebuild history + spend per user ID
  db = prev;
  return d;
}

function loadDB() {
  try {
    if (!fs.existsSync(DB_PATH)) {
      fs.writeFileSync(DB_PATH, JSON.stringify(emptyDB(), null, 2));
      return emptyDB();
    }
    return migrate(JSON.parse(fs.readFileSync(DB_PATH, 'utf8')));
  } catch (err) {
    console.error('Could not read orders.json, starting fresh:', err);
    return emptyDB();
  }
}
db = loadDB();

/** Saves to disk. If a `reason` is given, a backup is also posted to the backup channel. */
function saveDB(reason) {
  try {
    const tmp = DB_PATH + '.tmp';
    fs.writeFileSync(tmp, JSON.stringify(db, null, 2));
    fs.renameSync(tmp, DB_PATH); // atomic write: the file can never be half-written
  } catch (err) {
    console.error('Failed to save orders.json:', err);
  }
  if (reason) queueBackup(reason);
}

