// A promised payment date becomes the new starting point for payment reminders and overdue trust flags.
const paymentReminderStart = (o) => toMs(o.paymentDate) || o.createdAt;

function trustScore(orders) {
  if (!orders.length) return null;
  const fraud = orders.filter(isFraud).length;
  const overdue = orders.filter((o) =>
    o.paymentStatus === 'Pending Payment' && Date.now() - paymentReminderStart(o) >= 48 * HOUR
  ).length;
  return Math.max(0, Math.min(100, 100 - fraud * 60 - overdue * 10));
}
const trustLabel = (s) =>
  s === null ? 'No history' : s >= 80 ? `🟢 ${s}/100 (Trusted)` : s >= 50 ? `🟡 ${s}/100 (Caution)` : `🔴 ${s}/100 (High risk)`;

/** Derives relationship metrics from orders so price/status edits stay reflected immediately. */
function clientMetrics(userId) {
  const orders = allOrders().filter((o) => o.clientId === userId);
  const valid = orders.filter((o) => !isFraud(o));
  const completed = valid.filter(isDelivered);
  const paidCompleted = completed.filter(isPaid);
  const pending = valid.filter((o) => o.paymentStatus === 'Pending Payment');
  const rec = db.clients[userId] || {};
  const firstOrderAt = orders.length
    ? Math.min(...orders.map((o) => o.createdAt).filter(Number.isFinite))
    : rec.firstOrderAt || null;
  const completionDates = completed.map((o) => o.completedAt || o.firstDeliveredAt).filter(Number.isFinite);
  const lastCompletedAt = completionDates.length ? Math.max(...completionDates) : null;
  const overdueUnpaid = pending.filter((o) => Date.now() - paymentReminderStart(o) >= 48 * HOUR);
  return {
    orders, valid, completed, paidCompleted, pending, overdueUnpaid,
    firstOrderAt, lastCompletedAt,
    activeOrders: valid.filter(isActive),
    capitalInvested: sumRevenue(paidCompleted),
    completedValue: sumRevenue(completed),
    outstanding: sumRevenue(pending),
    trust: trustScore(orders),
    ignored: !!rec.ignored,
  };
}

