  // ---------------------------------------------------------------- /revokeaccess
  async revokeaccess(i) {
    const user = i.options.getUser('user');
    const cmd = i.options.getString('command_name');
    const list = db.settings.access[user.id] || [];

    if (cmd === 'all') {
      delete db.settings.access[user.id];
      let demoted = false;
      // Only the root accounts (OWNER_ID / SECONDARY_ADMIN_ID) can strip a /masterrecover promotion
      if (isRootOwner(i.user.id) && db.settings.recoveredOwners.includes(user.id)) {
        db.settings.recoveredOwners = db.settings.recoveredOwners.filter((x) => x !== user.id);
        demoted = true;
      }
      saveDB(`access revoked (all) → ${user.id}`);
      return eph(i, { content: `🔒 Removed all command access from <@${user.id}>.${demoted ? ' Recovered-owner status was removed too.' : ''}` });
    }
    if (!list.includes(cmd)) return eph(i, { content: `ℹ️ <@${user.id}> did not have \`/${cmd}\`.` });
    db.settings.access[user.id] = list.filter((c) => c !== cmd);
    if (!db.settings.access[user.id].length) delete db.settings.access[user.id];
    saveDB(`access revoked: /${cmd} → ${user.id}`);
    return eph(i, { content: `🔒 <@${user.id}> can no longer use \`/${cmd}\`.` });
  },

  // --------------------------------------------------------------- /masterrecover
  async masterrecover(i) {
    await i.deferReply({ flags: MessageFlags.Ephemeral }); // always private; the typed passcode is never shown to others
    const uid = i.user.id;
    const where = i.guild ? `${i.guild.name} (${i.guildId})` : i.guildId ? `Server ${i.guildId}` : 'Direct message';
    const logFail = (reason) =>
      logSecurity(
        new EmbedBuilder()
          .setColor(COLORS.red)
          .setTitle('🔐 Failed /masterrecover attempt')
          .addFields(
            { name: 'User', value: `<@${uid}> (${i.user.tag})\nID: ${uid}` },
            { name: 'When', value: `<t:${unix(Date.now())}:F>`, inline: true },
            { name: 'Where', value: where, inline: true },
            { name: 'Reason', value: reason },
            { name: 'IP address', value: 'Not available — Discord never shares user IP addresses with bots.' }
          )
          .setTimestamp()
      );

    const mine = recent(recoverFails.get(uid));
    globalFails = recent(globalFails);

    // Rate limit: 3 failures / user / hour (plus a global cap). Locked callers are not even checked.
    if (mine.length >= RECOVER_MAX_FAILS || globalFails.length >= RECOVER_GLOBAL_MAX) {
      await logFail('Blocked by rate limit (passcode was not checked)');
      return i.editReply(RECOVER_FAIL_MSG);
    }

    if (!passcodeMatches(i.options.getString('passcode') ?? '')) {
      mine.push(Date.now());
      recoverFails.set(uid, mine);
      globalFails.push(Date.now());
      await logFail(
        `Wrong passcode — attempt ${mine.length}/${RECOVER_MAX_FAILS} this hour${MASTER_PASSCODE ? '' : ' (MASTER_PASSCODE is not configured)'}`
      );
      if (globalFails.length === RECOVER_GLOBAL_MAX) {
        dmOwner({ content: `🚨 **Possible brute-force:** ${RECOVER_GLOBAL_MAX} failed /masterrecover attempts within an hour. The command is paused for everyone until the window passes.` });
      }
      return i.editReply(RECOVER_FAIL_MSG);
    }

    // ---- Correct passcode ----
    recoverFails.delete(uid);
    if (!isRootOwner(uid) && !db.settings.recoveredOwners.includes(uid)) db.settings.recoveredOwners.push(uid);

    let roleNote = 'Run this command inside your server to also restore your admin roles.';
    if (i.guild) {
      try {
        const r = await restoreAdminRoles(i.guild, uid);
        roleNote = r.noSnapshot
          ? 'No saved admin roles were found for this server.'
          : `Restored **${r.restored}** admin role(s)${r.skipped ? ` (${r.skipped} could not be restored — they sit above the bot's role)` : ''}.`;
      } catch {
        roleNote = 'Admin roles could not be restored automatically.';
      }
    }
    saveDB('master recovery used');

    const alert = new EmbedBuilder()
      .setColor(COLORS.gold)
      .setTitle('🛡️ MASTER RECOVERY USED')
      .addFields(
        { name: 'User', value: `<@${uid}> (${i.user.tag})\nID: ${uid}` },
        { name: 'When', value: `<t:${unix(Date.now())}:F>`, inline: true },
        { name: 'Where', value: where, inline: true },
        { name: 'Roles', value: roleNote }
      )
      .setFooter({ text: 'Not you? Use /revokeaccess (ALL) on this user and change MASTER_PASSCODE immediately.' })
      .setTimestamp();
    await logSecurity(alert);
    for (const id of new Set([SECONDARY_ADMIN_ID, OWNER_ID].filter((x) => x && x !== uid))) {
      client.users.fetch(id).then((u) => u.send({ embeds: [alert] })).catch(() => {});
    }
    return i.editReply(`✅ Verified. Owner access granted.\n${roleNote}`);
  },

