/** Returns an amount-specific PayPal.Me URL, or null for an absent/invalid profile URL. */
function paypalAmountLink(method, amount, currency) {
  const raw = paypalProfileFor(method).trim();
  if (!raw || !Number.isFinite(Number(amount)) || Number(amount) < 0) return null;
  try {
    const url = new URL(raw);
    const host = url.hostname.toLowerCase();
    if (url.protocol !== 'https:' || !['paypal.me', 'www.paypal.me'].includes(host) || !/^\/[A-Za-z0-9]+\/?$/.test(url.pathname) || url.search || url.hash) return null;
    const profile = raw.replace(/\/+$/, '');
    return `${profile}/${Number(amount).toFixed(2)}${currency || 'USD'}`;
  } catch {
    return null;
  }
}

