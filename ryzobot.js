const roundMoney = (n) => Math.round((Number(n) + Number.EPSILON) * 100) / 100;
const fmtMoney = (n, c) => (c === 'EUR' ? `€${Number(n || 0).toFixed(2)}` : `$${Number(n || 0).toFixed(2)}`);

/**
 * Calculates what the client must pay while keeping the agreed order price separate.
 * Tax is calculated on the agreed price. PayPal fees are grossed up so the agreed
 * price plus tax is not reduced by the configured processing fee. These extra
 * amounts are invoice charges only; all revenue/statistics continue to use o.price.
 */
function invoiceAmounts(o) {
  const base = roundMoney(Math.max(0, Number(o.price) || 0));
  const tax = roundMoney(base * SALES_TAX_RATE / 100);
  const isPayPal = o.paymentMethod === 'PayPal 1' || o.paymentMethod === 'PayPal 2';
  const feePercent = isPayPal ? PAYPAL_FEE_PERCENT : 0;
  const feeFixed = isPayPal
    ? (o.currency === 'EUR' ? PAYPAL_FEE_FIXED_EUR : PAYPAL_FEE_FIXED_USD)
    : 0;
  const beforeProcessing = roundMoney(base + tax);
  const total = roundMoney(feePercent > 0
    ? (beforeProcessing + feeFixed) / (1 - feePercent / 100)
    : beforeProcessing + feeFixed);
  const processingFee = roundMoney(Math.max(0, total - beforeProcessing));
  return { base, tax, taxRate: SALES_TAX_RATE, processingFee, total, feePercent, feeFixed };
}

