    const imageUrl = i.options.getString('image_url');
    const thumbnailUrl = i.options.getString('thumbnail_url');
    const validHttps = (value) => {
      if (!value) return true;
      try { return new URL(value).protocol === 'https:'; } catch { return false; }
    };
    if (!validHttps(imageUrl) || !validHttps(thumbnailUrl)) {
      return eph(i, { content: '❌ Image and thumbnail links must be valid HTTPS URLs.' });
    }

    const embed = new EmbedBuilder()
      .setColor(color)
      .setAuthor({ name: i.guild?.name || BRAND })
      .setTitle(i.options.getString('title').trim())
      .setDescription(i.options.getString('message').replace(/\\n/g, '\n').trim())
      .setFooter({ text: (i.options.getString('footer') || BRAND).slice(0, 2048) })
      .setTimestamp();
    if (imageUrl) embed.setImage(imageUrl);
    if (thumbnailUrl) embed.setThumbnail(thumbnailUrl);

    try {
      await channel.send({ embeds: [embed], allowedMentions: { parse: [] } });
    } catch (err) {
      console.error('Could not publish /post embed:', err);
      return eph(i, { content: "❌ I couldn't publish the post. Check the bot's View Channel, Send Messages, and Embed Links permissions, and verify the image URLs." });
    }
    return eph(i, { content: `✅ Custom embed published in <#${channel.id}>.` });
