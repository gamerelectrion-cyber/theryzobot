function readNonNegativeEnv(name, fallback = 0) {
  const raw = process.env[name];
  if (raw === undefined || raw.trim() === '') return fallback;
  const value = Number(raw);
  if (!Number.isFinite(value) || value < 0) {
    console.warn(`⚠️ ${name} must be a non-negative number. Using ${fallback}.`);
    return fallback;
  }
  return value;
}
function readPercentEnv(name, fallback = 0) {
  const value = readNonNegativeEnv(name, fallback);
  if (value >= 100) {
    console.warn(`⚠️ ${name} must be below 100. Using ${fallback}.`);
    return fallback;
  }
  return value;
}
