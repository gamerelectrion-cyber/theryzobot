const sha256 = (v) => crypto.createHash('sha256').update(String(v)).digest();
/** Constant-time comparison so response timing can't leak the passcode. */
function passcodeMatches(input) {
  if (!MASTER_PASSCODE) return false;
  return crypto.timingSafeEqual(sha256(input), sha256(MASTER_PASSCODE));
}
const recent = (arr = []) => arr.filter((t) => Date.now() - t < RECOVER_WINDOW_MS);

