let backupTimer = null;
let backupReasons = [];

function queueBackup(reason) {
  if (!BACKUP_CHANNEL_ID || !client.isReady()) return;
  backupReasons.push(reason);
  clearTimeout(backupTimer);
  backupTimer = setTimeout(sendBackup, 5000); // groups rapid changes into one backup
}

async function sendBackup() {
  const reasons = [...new Set(backupReasons)].join(', ');
  backupReasons = [];
  try {
    const ch = await client.channels.fetch(BACKUP_CHANNEL_ID);
    const stamp = new Date().toISOString().replace(/[:.]/g, '-');
    const file = new AttachmentBuilder(Buffer.from(JSON.stringify(db, null, 2)), { name: `orders-backup-${stamp}.json` });
    await ch.send({ content: `🗄️ **Database backup** • ${reasons} • <t:${unix(Date.now())}:f>`, files: [file] });
  } catch (err) {
    console.error('Backup failed (check BACKUP_CHANNEL_ID and bot permissions):', err.message);
  }
}

/** If orders.json is missing (e.g. fresh host), restore the newest backup from the backup channel. */
async function restoreFromBackupIfNeeded() {
  if (dbFileExistedAtBoot || !BACKUP_CHANNEL_ID) return;
  try {
    const ch = await client.channels.fetch(BACKUP_CHANNEL_ID);
    const msgs = await ch.messages.fetch({ limit: 50 });
    const msg = msgs
      .filter((m) => m.author.id === client.user.id && m.attachments.some((a) => a.name?.endsWith('.json')))
      .first();
    if (!msg) return;
    const att = msg.attachments.find((a) => a.name?.endsWith('.json'));
    const data = await (await fetch(att.url)).json();
    db = migrate(data);
    saveDB();
    console.log('Database restored from the latest backup in the backup channel.');
  } catch (err) {
    console.error('Auto-restore failed:', err.message);
  }
}

