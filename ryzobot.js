/**
 * Marks an order as delivered. On the FIRST delivery, if it beats the deadline,
 * the bot logs an Early Finish and stores how many hours early it was.
 * Returns { early (hours or null), status (final workStatus) }.
 */
function finishOrder(o, requested) {
  const now = Date.now();
  let early = null;
  if (!o.firstDeliveredAt) {
    o.firstDeliveredAt = now; // on-time checks always use the FIRST delivery
    if (o.deadlineAt && now < o.deadlineAt) {
      o.earlyFinishHours = Math.round(((o.deadlineAt - now) / HOUR) * 10) / 10;
      early = o.earlyFinishHours;
      o.log.push({ at: now, event: `Early Finish: ${early}h before the deadline` });
    }
  }
  o.completedAt = now;
  // 'Completed Early' is only valid if the order really was early; otherwise plain 'Completed'
  o.workStatus = requested === 'Completed Early' && o.earlyFinishHours != null ? 'Completed Early' : 'Completed';
  return { early, status: o.workStatus };
}

/** Makes this the ONE order you are working on. Any other active order goes back to the queue. */
function setActive(o) {
  const demoted = [];
  for (const x of allOrders()) {
    if (x.id !== o.id && x.workStatus === 'Active') {
      x.workStatus = 'In Progress';
      x.log.push({ at: Date.now(), event: 'Moved back to queue (another order became active)' });
      demoted.push(x.id);
    }
  }
  o.workStatus = 'Active';
  o.workStartedAt = Date.now();
  o.log.push({ at: Date.now(), event: 'Set as active work' });
  return demoted;
}

/** Returns an error message if the order can't be moved around the queue, otherwise null. */
function queueBlock(o) {
  if (isFraud(o)) return `🚨 Order **#${o.id}** is flagged as fraud and is excluded from the queue.`;
  if (isFinished(o)) {
    return `✅ Order **#${o.id}** is already completed. If the client wants changes, use \`/updatestatus\` → In Revision.`;
  }
  return null;
}

function queueLine(o, n, pub = false) {
  const due = !o.deadlineAt
    ? 'no deadline'
    : !isDelivered(o) && o.deadlineAt < Date.now()
      ? `🔴 overdue since <t:${unix(o.deadlineAt)}:R>`
      : `due <t:${unix(o.deadlineAt)}:R>`;
  const num = n ? `${n}. ` : '';
  // Public view (ticket channels) never shows other clients' names, prices or payment status
  if (pub) return `${num}**#${o.id}** • ${due}`;
  const pay = isPaid(o) ? '💚 Paid' : '💳 Unpaid';
  return `${num}**#${o.id}** • ${o.clientName} • ${fmtMoney(o.price, o.currency)} • ${due} • ${pay}`;
}

/** Keeps a list inside Discord's 1024-character field limit. */
function fitField(lines, empty) {
  if (!lines.length) return empty;
  let out = '';
  let shown = 0;
  for (const l of lines) {
    if ((out + l + '\n').length > 950) break;
    out += l + '\n';
    shown++;
  }
  if (shown < lines.length) out += `…and ${lines.length - shown} more`;
  return out.trim();
}

/**
 * The live pipeline board shown by /queue.
 * publicView = true (used for the "Public / Ticket" target) hides client names, prices and payment info.
 */
function buildQueueEmbed(publicView = false) {
  const open = allOrders().filter(isActive); // not fraud, not (paid AND finished)
  const byDeadline = (a, b) => (a.deadlineAt ?? Infinity) - (b.deadlineAt ?? Infinity);

  const active = open.filter((o) => o.workStatus === 'Active').sort(byDeadline);
  const upNext = open.filter((o) => o.workStatus === 'In Progress').sort(byDeadline); // earliest deadline first
  const ready = open.filter(isFinished).sort((a, b) => (b.completedAt ?? 0) - (a.completedAt ?? 0));
  const trouble = open.filter((o) => o.workStatus === 'Delayed' || o.workStatus === 'In Revision').sort(byDeadline);

  // Positions (1., 2., 3. ...) are generated fresh every time, so deleting an order renumbers the queue
  const line = (o, n) => queueLine(o, n, publicView);

  const activeLines = active.map((o) => line(o) + (o.workStartedAt ? `\n↳ 🛠️ working since <t:${unix(o.workStartedAt)}:R>` : ''));
  const upNextLines = upNext.map((o, idx) => line(o, idx + 1));
  const readyLines = ready.map((o) => {
    const tag = o.workStatus === 'Completed Early' && o.earlyFinishHours != null ? `⚡ ${o.earlyFinishHours}h early` : '✅ delivered';
    if (publicView) return `**#${o.id}** • ${tag}`;
    return `**#${o.id}** • ${o.clientName} • ${fmtMoney(o.price, o.currency)} • ${tag} • ${isPaid(o) ? '💚 Paid' : '💳 Unpaid'}`;
  });
  const troubleLines = trouble.map((o) => {
    const note = o.workStatus === 'Delayed' ? o.delayReason : o.notes;
    const why = !publicView && note ? ` — ${note.slice(0, 60)}${note.length > 60 ? '…' : ''}` : '';
    return `${line(o)}\n↳ ${o.workStatus === 'Delayed' ? '⏳ Delayed' : '🔁 Revision needed'}${why}`;
  });

  const toFinish = active.length + upNext.length + trouble.length;
  const unpaid = open.filter((o) => o.paymentStatus === 'Pending Payment').length;

  return new EmbedBuilder()
    .setColor(active.length ? COLORS.green : COLORS.main)
    .setTitle(publicView ? `🎨 ${BRAND} — Live Work Queue` : '🎨 Live Work Queue')
    .setDescription(
      publicView
        ? `📦 **${toFinish}** to finish • ✅ **${ready.length}** ready/delivered`
        : `📦 **${toFinish}** to finish • ✅ **${ready.length}** ready/delivered • 💳 **${unpaid}** unpaid`
    )
    .addFields(
      { name: `🟢 Working On Right Now (${active.length})`, value: fitField(activeLines, '*Nothing active right now*') },
      { name: `🟡 In Queue / Up Next (${upNext.length})`, value: fitField(upNextLines, '*Queue is empty*') },
      { name: `🔵 Completed Early / Ready for Delivery (${ready.length})`, value: fitField(readyLines, '*Nothing waiting*') },
      { name: `🔴 Delayed / Revision Needed (${trouble.length})`, value: fitField(troubleLines, '*All clear ✨*') }
    )
    .setFooter({ text: publicView ? 'Times update live' : 'Up Next is sorted by earliest deadline' })
    .setTimestamp();
}

