// Anti-nuke protection (mass ban / kick / channel deletion)
// ---------------------------------------------------------------------------
const nukeLog = new Map(); // "guildId:executorId:action" -> timestamps
const recentlyPunished = new Set();

client.on(Events.GuildAuditLogEntryCreate, async (entry, guild) => {
  let type;
  if (entry.action === AuditLogEvent.MemberBanAdd) type = 'mass-banning members';
  else if (entry.action === AuditLogEvent.MemberKick) type = 'mass-kicking members';
  else if (entry.action === AuditLogEvent.ChannelDelete) type = 'mass-deleting channels';
  else return;

  const executorId = entry.executorId;
  if (!executorId || executorId === client.user.id) return;
  if (executorId === guild.ownerId || isOwnerLevel(executorId)) return; // trusted people are exempt

  const key = `${guild.id}:${executorId}:${entry.action}`;
  const now = Date.now();
  const hits = (nukeLog.get(key) || []).filter((t) => now - t < NUKE_WINDOW_MS);
  hits.push(now);
  nukeLog.set(key, hits);

  if (hits.length < NUKE_LIMIT || recentlyPunished.has(`${guild.id}:${executorId}`)) return;
  nukeLog.delete(key);
  recentlyPunished.add(`${guild.id}:${executorId}`);
  setTimeout(() => recentlyPunished.delete(`${guild.id}:${executorId}`), 60_000);

  let removed = 0;
  let failed = 0;
  const member = await guild.members.fetch(executorId).catch(() => null);
  if (member) {
    const roles = member.roles.cache.filter((r) => r.id !== guild.id);
    const editable = roles.filter((r) => r.editable && !r.managed);
    failed = roles.size - editable.size;
    try {
      await member.roles.remove(editable, `Anti-nuke: ${type}`);
      removed = editable.size;
    } catch {
      failed += editable.size;
    }
  }

  const embed = new EmbedBuilder()
    .setColor(COLORS.red)
    .setTitle('🚨 ANTI-NUKE TRIGGERED')
    .setDescription(`<@${executorId}> was caught **${type}** (${hits.length}+ actions in ${NUKE_WINDOW_MS / 1000}s) in **${guild.name}**.`)
    .addFields(
      { name: 'Roles removed', value: String(removed), inline: true },
      { name: 'Roles I could not remove', value: String(failed), inline: true },
      { name: 'Next step', value: 'Review the Audit Log and consider kicking/banning this account.' }
    )
    .setTimestamp();

  for (const id of ownerTargets()) {
    client.users.fetch(id).then((u) => u.send({ embeds: [embed] })).catch(() => {});
  }
});

