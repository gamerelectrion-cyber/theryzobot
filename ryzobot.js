/** Payment reminders: DM at 24h and again at 48h if still unpaid (unless silenced). */
async function checkPayments() {
  let changed = false;
  for (const o of allOrders()) {
    if (o.paymentStatus !== 'Pending Payment' || o.ignorePayment) continue;
    const reminderStart = paymentReminderStart(o);
    if (o.paymentDate && Date.now() < reminderStart) continue; // promised date has not arrived yet
    const age = Date.now() - reminderStart;
    const stage = age >= 48 * HOUR ? 2 : age >= 24 * HOUR ? 1 : 0;
    if (stage <= o.reminderStage) continue;

    o.reminderStage = stage;
    changed = true;
    await dmOwner({
      embeds: [
        new EmbedBuilder()
          .setColor(COLORS.orange)
          .setTitle(`💸 Payment still pending — #${o.id}`)
          .setDescription(`Order is **${Math.floor(age / HOUR)} hours** old and not paid yet.`)
          .addFields(
            { name: 'Client', value: `<@${o.clientId}> (${o.clientName})`, inline: true },
            { name: 'Amount', value: fmtMoney(o.price, o.currency), inline: true },
            { name: 'Method', value: o.paymentMethod, inline: true },
            { name: 'Silence this?', value: `Use \`/ignorepayment order_id:${o.id}\`` }
          )
          .setTimestamp(),
      ],
    });
  }
  if (changed) saveDB();
}

/** Deadline alerts: warning under 6h left, and an alert when a deadline is missed. */
async function checkDeadlines() {
  let changed = false;
  for (const o of allOrders()) {
    if (isFraud(o) || isDelivered(o) || !o.deadlineAt || ['In Revision', 'Completed', 'Completed Early'].includes(o.workStatus)) continue;
    const left = o.deadlineAt - Date.now();

    if (left <= 0 && !o.missedAlerted) {
      o.missedAlerted = o.warned6h = true;
      changed = true;
      await dmOwner({
        embeds: [
          new EmbedBuilder()
            .setColor(COLORS.red)
            .setTitle(`🚨 DEADLINE MISSED — #${o.id}`)
            .addFields(
              { name: 'Client', value: `<@${o.clientId}> (${o.clientName})`, inline: true },
              { name: 'Status', value: o.workStatus, inline: true },
              { name: 'Overdue by', value: duration(-left), inline: true },
              { name: 'Logged reason', value: o.delayReason || 'None logged — use `/updatestatus` with status Delayed and a reason.' }
            )
            .setTimestamp(),
        ],
      });
    } else if (left > 0 && left <= 6 * HOUR && !o.warned6h) {
      o.warned6h = true;
      changed = true;
      await dmOwner({
        embeds: [
          new EmbedBuilder()
            .setColor(COLORS.orange)
            .setTitle(`⏰ URGENT: under 6 hours left — #${o.id}`)
            .addFields(
              { name: 'Client', value: `<@${o.clientId}> (${o.clientName})`, inline: true },
              { name: 'Time left', value: duration(left), inline: true },
              { name: 'Status', value: o.workStatus, inline: true }
            )
            .setTimestamp(),
        ],
      });
    }
  }
  if (changed) saveDB();
}

/** Builds a business summary for any time window. */
function buildReport(title, from, to) {
  const all = allOrders();
  const valid = validOrders();
  const created = valid.filter((o) => o.createdAt >= from && o.createdAt < to);
  const rev = sumRevenue(paidBetween(from, to));
  const deliveredIn = valid.filter((o) => isDelivered(o) && o.firstDeliveredAt >= from && o.firstDeliveredAt < to);
  const onTime = deliveredIn.filter(isOnTime).length;
  const earlyCount = deliveredIn.filter((o) => o.earlyFinishHours > 0).length; // NEW
  const newClients = Object.values(db.clients).filter((c) => c.firstOrderAt >= from && c.firstOrderAt < to).length;
  const fraud = all.filter((o) => isFraud(o) && o.createdAt >= from && o.createdAt < to).length;
  const unpaid = sumRevenue(valid.filter((o) => o.paymentStatus === 'Pending Payment'));
  const cycle = sumRevenue(valid.filter((o) => isPaid(o) && !o.paidOut));

  return new EmbedBuilder()
    .setColor(COLORS.gold)
    .setTitle(title)
    .setDescription(`<t:${unix(from)}:D> → <t:${unix(to)}:D>`)
    .addFields(
      { name: '💰 Revenue in period', value: fmtBoth(rev) },
      { name: '🆕 New orders', value: String(created.length), inline: true },
      { name: '✅ Delivered', value: String(deliveredIn.length), inline: true },
      { name: '⏱️ On-time / Late', value: `${onTime} / ${deliveredIn.length - onTime}`, inline: true },
      { name: '👥 New clients', value: String(newClients), inline: true },
      { name: '🚨 Fraud cases', value: String(fraud), inline: true },
      { name: '📋 Active orders now', value: String(all.filter(isActive).length), inline: true },
      { name: '⚡ Early finishes', value: String(earlyCount), inline: true },
      { name: '⏳ Outstanding unpaid', value: fmtBoth(unpaid) },
      { name: '🏦 Current payout cycle', value: fmtBoth(cycle) }
    )
    .setTimestamp();
}

async function sendReport(kind) {
  const now = Date.now();
  const embed =
    kind === 'weekly'
      ? buildReport('📈 Weekly Business Report', now - 7 * DAY, now)
      : buildReport('📆 Monthly Business Report', monthStart(-1), monthStart(0));

  const ch = REPORT_CHANNEL_ID ? await fetchSendable(REPORT_CHANNEL_ID) : null;
  if (ch) await ch.send({ embeds: [embed] }).catch((e) => console.error('Report failed:', e.message));
  else await dmOwner({ embeds: [embed] }); // fallback if REPORT_CHANNEL_ID is missing
}

